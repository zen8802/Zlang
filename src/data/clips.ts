export function getClipById(id: string): ClipData | undefined {
  return clips.find(c => c.id === id)
}

export function getClipsByLanguage(language: 'japanese' | 'english'): ClipData[] {
  return clips.filter(c => c.language === language)
}

export function getClipsByCategory(category: string): ClipData[] {
  return clips.filter(c => c.categories.includes(category))
}

export function getClipsByLevel(level: string): ClipData[] {
  return clips.filter(c => c.level === level)
}

export function getClipsForUser(
  targetLanguage: 'japanese' | 'english',
  level: string,
  interests: string[]
): ClipData[] {
  const langClips = getClipsByLanguage(targetLanguage)
  const levelClips = langClips.filter(c => c.level === level)
  const interestClips = levelClips.filter(c =>
    c.categories.some(cat => interests.includes(cat))
  )
  return interestClips.length > 0 ? interestClips : levelClips
}
