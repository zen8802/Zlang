export function getLessonById(id: string): LessonData | undefined {
  return lessons.find(l => l.id === id)
}

export function getLessonsByCorridor(corridor: Corridor): LessonData[] {
  return lessons.filter(l => l.corridor === corridor)
}

export function getLessonsByUnit(corridor: Corridor, unit: number): LessonData[] {
  return lessons.filter(l => l.corridor === corridor && l.unit === unit)
}

export function getNextLesson(completedIds: string[]): LessonData | undefined {
  const completedSet = new Set(completedIds)

  // Try EN→JP first, then JP→EN
  for (const corridor of ['en-to-jp', 'jp-to-en'] as Corridor[]) {
    const corridorLessons = getLessonsByCorridor(corridor)
      .sort((a, b) => a.lessonNumber - b.lessonNumber)

    for (const lesson of corridorLessons) {
      if (!completedSet.has(lesson.id)) {
        return lesson
      }
    }
  }

  return undefined
}

export function getNextLessonForCorridor(
  corridor: Corridor,
  completedIds: string[]
): LessonData | undefined {
  const completedSet = new Set(completedIds)
  const corridorLessons = getLessonsByCorridor(corridor)
    .sort((a, b) => a.lessonNumber - b.lessonNumber)

  for (const lesson of corridorLessons) {
    if (!completedSet.has(lesson.id)) {
      return lesson
    }
  }

  return undefined
}

export function getUnitProgress(
  corridor: Corridor,
  unit: number,
  completedIds: string[]
): { total: number; completed: number; percentage: number } {
  const unitLessons = getLessonsByUnit(corridor, unit)
  const completedSet = new Set(completedIds)
  const completed = unitLessons.filter(l => completedSet.has(l.id)).length

  return {
    total: unitLessons.length,
    completed,
    percentage: unitLessons.length > 0 ? Math.round((completed / unitLessons.length) * 100) : 0,
  }
}
